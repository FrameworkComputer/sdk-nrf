/* Input report layouts of the touchpad. Offsets exclude the report ID. */
#define DAISY_TP_MOUSE_REPORT_ID	1	/* buttons in bits 0-1 of byte 0 */
#define DAISY_TP_PTP_REPORT_ID		4
#define DAISY_TP_PTP_CONTACTS		5	/* 5 bytes each: flags (bit 1 = tip), X, Y */
#define DAISY_TP_PTP_CONTACT_SIZE	5
#define DAISY_TP_PTP_CONTACT_COUNT_OFS	25
#define DAISY_TP_PTP_BUTTON_OFS		26	/* bit 0 */
#define DAISY_TP_PTP_SCAN_TIME_OFS	27	/* u16, 100 us units */
/* The pad reports every 7.1 ms. */
#define DAISY_TP_PTP_FRAME_TIME		71

/* Whether an input report of an exclusive interface has nothing pressed.
 * report[0] is the report ID.
 */
static bool hid_passthrough_report_idle(size_t iface, const uint8_t *report, size_t size)
{
	ARG_UNUSED(iface);

	const uint8_t *r = &report[1];

	if ((report[0] == DAISY_TP_MOUSE_REPORT_ID) && (size > 1)) {
		return !(r[0] & 0x03);
	}

	if ((report[0] == DAISY_TP_PTP_REPORT_ID) && (size > (1 + DAISY_TP_PTP_BUTTON_OFS))) {
		if (r[DAISY_TP_PTP_BUTTON_OFS] & 0x01) {
			return false;
		}

		uint8_t n = MIN(r[DAISY_TP_PTP_CONTACT_COUNT_OFS], DAISY_TP_PTP_CONTACTS);

		for (uint8_t i = 0; i < n; i++) {
			if (r[i * DAISY_TP_PTP_CONTACT_SIZE] & 0x02) {
				return false;
			}
		}
	}

	return true;
}

/* Turn the last input report the host got into one that lets go: no buttons,
 * and in a PTP frame every contact's tip up where it was (how the pad itself
 * reports a lift), one frame later.
 */
static void hid_passthrough_report_lift(size_t iface, uint8_t *report, size_t size)
{
	ARG_UNUSED(iface);

	uint8_t *r = &report[1];

	if (report[0] == DAISY_TP_MOUSE_REPORT_ID) {
		memset(r, 0, size - 1);
		return;
	}

	if ((report[0] != DAISY_TP_PTP_REPORT_ID) ||
	    (size < (1 + DAISY_TP_PTP_SCAN_TIME_OFS + sizeof(uint16_t)))) {
		return;
	}

	for (uint8_t i = 0; i < DAISY_TP_PTP_CONTACTS; i++) {
		r[i * DAISY_TP_PTP_CONTACT_SIZE] &= ~0x02;
	}
	r[DAISY_TP_PTP_BUTTON_OFS] = 0;
	sys_put_le16(sys_get_le16(&r[DAISY_TP_PTP_SCAN_TIME_OFS]) + DAISY_TP_PTP_FRAME_TIME,
		     &r[DAISY_TP_PTP_SCAN_TIME_OFS]);
}
